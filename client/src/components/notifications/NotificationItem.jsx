// Default icon for unknown notification types
const defaultIcon = (
  <svg xmlns="http://www.w3.org/2000/svg" className="h-6 w-6 text-gray-500" fill="none" viewBox="0 0 24 24" stroke="currentColor">
    <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M15 17h5l-1.405-1.405A2.032 2.032 0 0118 14.158V11a6.002 6.002 0 00-4-5.659V5a2 2 0 10-4 0v.341C7.67 6.165 6 8.388 6 11v3.159c0 .538-.214 1.055-.595 1.436L4 17h5m6 0v1a3 3 0 11-6 0v-1m6 0H9" />
  </svg>
);

// Priority colors
const priorityColors = {
  low: 'bg-gray-100',
  medium: 'bg-blue-100',
  high: 'bg-amber-100',
  urgent: 'bg-rose-100'
};

const NotificationItem = ({ notification, onClose }) => {
  const dispatch = useDispatch();
  const { _id, title, message, type, isRead, link, createdAt, priority, sender, project } = notification;
  
  // Format date
  const formattedDate = new Date(createdAt).toLocaleString();
  
  // Handle mark as read
  const handleMarkAsRead = (e) => {
    e.stopPropagation();
    if (!isRead) {
      dispatch(markAsRead(_id));
    }
  };
  
  // Handle delete
  const handleDelete = (e) => {
    e.stopPropagation();
    dispatch(deleteNotification(_id));
  };
  
  // Handle click on notification
  const handleClick = () => {
    // Mark as read if not already read
    if (!isRead) {
      dispatch(markAsRead(_id));
    }
    
    // Close notification dropdown if provided
    if (onClose) {
      onClose();
    }
  };
  
  return (
    <div 
      className={`relative p-4 border-b last:border-b-0 transition-colors duration-200 hover:bg-gray-50 cursor-pointer ${!isRead ? 'bg-blue-50' : ''}`}
      onClick={handleClick}
    >
      <Link to={link || '#'} className="block">
        <div className="flex">
          {/* Icon */}
          <div className={`mr-3 flex-shrink-0 rounded-full p-2 ${priorityColors[priority] || 'bg-gray-100'}`}>
            {typeIcons[type] || defaultIcon}
          </div>
          
          {/* Content */}
          <div className="flex-grow">
            <div className="flex justify-between items-start">
              <h4 className={`font-medium ${!isRead ? 'text-blue-800' : 'text-gray-800'}`}>
                {title}
              </h4>
              <span className="text-xs text-gray-500 whitespace-nowrap ml-2">
                {formattedDate}
              </span>
            </div>
            
            <p className={`text-sm mt-1 ${!isRead ? 'text-blue-700' : 'text-gray-600'}`}>
              {message}
            </p>
            
            {/* Metadata */}
            <div className="flex items-center mt-2 text-xs text-gray-500">
              {sender && (
                <div className="flex items-center mr-3">
                  <span className="mr-1">From:</span>
                  <span className="font-medium">{sender.name}</span>
                </div>
              )}
              
              {project && (
                <div className="flex items-center">
                  <span className="mr-1">Project:</span>
                  <span className="font-medium">{project.name}</span>
                </div>
              )}
            </div>
          </div>
        </div>
      </Link>
      
      {/* Actions */}
      <div className="absolute top-2 right-2 flex space-x-1">
        {!isRead && (
          <button 
            onClick={handleMarkAsRead}
            className="p-1 rounded-full hover:bg-gray-200 text-gray-500 hover:text-blue-600"
            title="Mark as read"
          >
            <svg xmlns="http://www.w3.org/2000/svg" className="h-4 w-4" fill="none" viewBox="0 0 24 24" stroke="currentColor">
              <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M5 13l4 4L19 7" />
            </svg>
          </button>
        )}
        <button 
          onClick={handleDelete}
          className="p-1 rounded-full hover:bg-gray-200 text-gray-500 hover:text-red-600"
          title="Delete"
        >
          <svg xmlns="http://www.w3.org/2000/svg" className="h-4 w-4" fill="none" viewBox="0 0 24 24" stroke="currentColor">
            <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M6 18L18 6M6 6l12 12" />
          </svg>
        </button>
      </div>
    </div>
  );
};

export default NotificationItem;